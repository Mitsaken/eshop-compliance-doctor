class EShopComplianceEngine {
  constructor() {
    this.checkpoints = COMPLIANCE_CHECKPOINTS;
  }

  auditPolicy(text, options = {}) {
    if (!text || typeof text !== "string" || text.trim().length === 0) {
      return {
        score: 0,
        grade: "F",
        passedCount: 0,
        failedCount: this.checkpoints.length,
        criticalViolations: this.checkpoints.filter(c => c.severity === "CRITICAL").length,
        results: []
      };
    }

    const storeType = (options && options.storeType) || "physical";
    const results = [];
    let totalWeightedScore = 0;
    let maxWeight = 0;

    for (const cp of this.checkpoints) {
      const weight = cp.severity === "CRITICAL" ? 3 : (cp.severity === "HIGH" ? 2 : 1);
      maxWeight += weight;

      const evalResult = cp.check(text, { storeType });
      totalWeightedScore += (evalResult.score * weight);
      const reg = RULE_REGISTRY_META[cp.id] || { ruleId: cp.id.toUpperCase(), effectiveFrom: "N/A", reviewStatus: "Base Statute" };

      results.push({
        id: cp.id,
        ruleId: reg.ruleId,
        effectiveFrom: reg.effectiveFrom,
        reviewStatus: reg.reviewStatus,
        category: cp.category,
        title: cp.title,
        lawRef: cp.lawRef,
        severity: cp.severity,
        penaltyRisk: cp.penaltyRisk,
        passed: evalResult.passed,
        score: evalResult.score,
        issue: evalResult.issue,
        recommendation: evalResult.recommendation,
        correctedClause: cp.correctedClause
      });
    }

    const finalScore = Math.round(totalWeightedScore / maxWeight);
    const criticalViolations = results.filter(r => !r.passed && r.severity === "CRITICAL").length;
    const failedCount = results.filter(r => !r.passed).length;
    const passedCount = results.filter(r => r.passed).length;

    let grade = "A";
    if (criticalViolations > 0 || finalScore < 60) grade = "F (Υψηλό Ρίσκο Μη Συμμόρφωσης)";
    else if (finalScore < 75) grade = "C (Απαιτούνται Άμεσες Διορθώσεις)";
    else if (finalScore < 90) grade = "B (Ικανοποιητικό με Μικρές Ελλείψεις)";
    else grade = "A (Συμβατό Βάσει Ελέγχου)";

    return {
      score: finalScore,
      grade,
      passedCount,
      failedCount,
      criticalViolations,
      results
    };
  }

  generateMarkdownReport(auditResult, storeName = "Ηλεκτρονικό Κατάστημα") {
    const dateStr = new Date().toLocaleDateString("el-GR");
    let md = `# Έκθεση Τεχνικού & Κανονιστικού Προελέγχου e-Shop\n\n`;
    md += `> **Επωνυμία / Store:** ${storeName}  \n`;
    md += `> **Ημερομηνία Ελέγχου:** ${dateStr} (Τελευταία Νομοθετική Επαλήθευση: 19/11/2026)  \n`;
    md += `> **Ελεγκτικό Πλαίσιο:** Ν. 2251/1994, ΑΚ 541-546/554, Ν. 4919/2022 (Γ.Ε.ΜΗ.), GDPR, Omnibus Ν. 4933/2022, Κανονισμός ΕΕ 2024/3228 (Κατάργηση ODR), Οδηγία EmpCo 2024/825 & Ν. 5317/2026 (Άρθρο 3ζα)  \n`;
    md += `> **Όριο Ελέγχου:** Εξετάστηκε αποκλειστικά το κείμενο που υποβλήθηκε. Δεν ελέγχεται το ζωντανό checkout/UX του καταστήματος.  \n`;
    md += `> **Δείκτης Τεχνικής Συμμόρφωσης:** **${auditResult.score} / 100** — **${auditResult.grade}**  \n\n`;

    md += `## 1. Σύνοψη Ευρημάτων Ελέγχου\n\n`;
    md += `| Κατηγορία | Πλήθος | Εκτίμηση |\n`;
    md += `|:---|---:|:---|\n`;
    md += `| [ΣΥΜΜΟΡΦΩΝΕΤΑΙ] Τυπική κάλυψη | ${auditResult.passedCount} / ${auditResult.results.length} | Επαρκής τεχνική κάλυψη |\n`;
    md += `| [ΚΡΙΣΙΜΟ] Ενδείξεις παράβασης | ${auditResult.criticalViolations} | Άμεσος κίνδυνος διοικητικής κύρωσης |\n`;
    md += `| [ΠΡΟΣΟΧΗ] Ελλείψεις προς προσαρμογή | ${auditResult.failedCount} | Απαιτείται επικαιροποίηση κειμένου |\n\n`;

    md += `## 2. Αναλυτικό Μητρώο Ελέγχου (${auditResult.results.length} Σημεία)\n\n`;
    auditResult.results.forEach((r, idx) => {
      const statusLabel = r.passed ? "ΣΥΜΜΟΡΦΩΝΕΤΑΙ" : (r.severity === "CRITICAL" ? "ΚΡΙΣΙΜΗ ΕΝΔΕΙΞΗ" : "ΠΡΟΣΟΧΗ");
      md += `### ${idx + 1}. [${r.ruleId} | ${statusLabel}] ${r.title}\n`;
      md += `- **Νομική Βάση:** ${r.lawRef}\n`;
      md += `- **Ισχύς / Κατάσταση Μητρώου:** Από ${r.effectiveFrom} · ${r.reviewStatus}\n`;
      md += `- **Βαρύτητα:** ${r.severity} | **Βαθμολογία:** ${r.score}%\n`;
      if (!r.passed) {
        md += `- **Εντοπισμένο Πρόβλημα:** ${r.issue}\n`;
        md += `- **Κανονιστικός Κίνδυνος:** ${r.penaltyRisk}\n`;
        md += `- **Σύσταση Προσαρμογής:** ${r.recommendation}\n`;
        md += `\n**Ενδεικτική Ρήτρα (ενημερωτικό πρότυπο — επαληθεύστε την ισχύουσα διατύπωση ΦΕΚ):**\n\`\`\`text\n${r.correctedClause}\n\`\`\`\n`;
      } else {
        md += `- **Διαπίστωση:** Δεν εντοπίστηκε τυπική παράβαση με βάση το υποβληθέν κείμενο.\n`;
      }
      md += `\n`;
    });

    md += `---\n*Σημείωση: Ανεξάρτητο τεχνικό εργαλείο προελέγχου κειμένου ενημερωτικού χαρακτήρα (eShop Compliance Audit — Conversionlogic). Δεν ελέγχει ζωντανές σελίδες/checkout και η απουσία ευρήματος δεν συνιστά επίσημη βεβαίωση συμμόρφωσης.*`;
    return md;
  }
}

